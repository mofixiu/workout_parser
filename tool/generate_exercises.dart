// Regenerates lib/src/data/exercises.g.dart from an exercise library JSON
// file shaped like {"exercises": [...], "aliases": {"alias": "id"}}.
//
//   dart run tool/generate_exercises.dart path/to/library.json
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/generate_exercises.dart <library.json>');
    exit(64);
  }
  final json = jsonDecode(File(args.single).readAsStringSync()) as Map<String, dynamic>;
  final exercises = (json['exercises'] as List).cast<Map<String, dynamic>>();
  final aliases = (json['aliases'] as Map).cast<String, String>();
  final ids = {for (final e in exercises) e['id'] as String};

  String lit(String s) =>
      "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_exercises.dart. Do not edit by hand.')
    ..writeln('//')
    ..writeln('// Exercise names and ids come from free-exercise-db')
    ..writeln('// (https://github.com/yuhonas/free-exercise-db, Unlicense).')
    ..writeln()
    ..writeln("import '../exercise_index.dart';")
    ..writeln()
    ..writeln('const builtInExercises = <IndexedExercise>[');
  for (final e in exercises) {
    final parts = [
      'id: ${lit(e['id'] as String)}',
      'name: ${lit(e['name'] as String)}',
      if (e['equipment'] != null) 'equipment: ${lit(e['equipment'] as String)}',
      if (e['curated'] == true) 'curated: true',
      if (e['tracking'] == 'duration') 'timed: true',
    ];
    out.writeln('  IndexedExercise(${parts.join(', ')}),');
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('const builtInAliases = <String, String>{');
  var skipped = 0;
  for (final MapEntry(:key, :value) in aliases.entries) {
    if (!ids.contains(value)) {
      skipped++;
      continue;
    }
    out.writeln('  ${lit(key)}: ${lit(value)},');
  }
  out.writeln('};');

  File('lib/src/data/exercises.g.dart').writeAsStringSync(out.toString());
  stdout.writeln(
    'Wrote ${exercises.length} exercises and ${aliases.length - skipped} aliases'
    '${skipped > 0 ? ' (skipped $skipped pointing at unknown ids)' : ''}.',
  );
}
